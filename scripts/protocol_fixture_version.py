#!/usr/bin/env python3
"""Keep test hellos on the current intentd protocol version.

Fake `client.hello` payloads that hard-coded an old protocolVersion kept passing
after the daemon moved on, so a version cap that hid script monitors from every
user went unnoticed (intent-hq/intent#7206). Tests use
`ProtocolFixtures.currentProtocolVersion` from IntentTests/CurrentProtocolVersion.swift
instead; this script maintains that file and its contract.

  sync   regenerate the file from PROTOCOL_VERSION at the newest intentd release
  check  fail when the file's protocol differs from the newest intentd release (network)
  lint   fail on a literal "protocolVersion" in IntentTests/ (the target that owns
         ProtocolFixtures) without a reasoned `// fixture-protocol-version: <reason>`
         comment (offline)

The iOS app has no daemon pin; it talks to whichever daemon the desktop bundles.
The reference is the newest published intentd release, prereleases included: that
is what the desktop alpha bundles, and newer daemons are the ones a version cap breaks.
"""

import argparse
import json
import os
from pathlib import Path
import re
import sys
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path("IntentTests/CurrentProtocolVersion.swift")
REPO = "intent-hq/intentd"
PROTOCOL_SOURCE = "crates/intent-transport/src/protocol.rs"
SCANNED_DIRS = ("IntentTests",)
ESCAPE_TOKEN = "fixture-protocol-version"

RUST_CONSTANT = re.compile(r'pub const PROTOCOL_VERSION:\s*&(?:\'static\s+)?str\s*=\s*"(\d+(?:\.\d+)+)";')
SOURCE_TAG = re.compile(r"^// source-tag: (\S+)$", re.M)
SWIFT_CONSTANT = re.compile(r'^    static let currentProtocolVersion = "([^"]+)"$', re.M)
# `"protocolVersion": "15.0"` dictionary entries and `protocolVersion: "15.0"` arguments.
LITERAL = re.compile(r'"?\bprotocolVersion"?\s*:\s*"(\d+(?:\.\d+)*)"')
ESCAPE = re.compile(r"//\s*" + ESCAPE_TOKEN + r":\s*\S")
COMMENT_ONLY = re.compile(r"^\s*//")


def parse_rust_protocol_version(source):
    matches = RUST_CONSTANT.findall(source)
    if len(matches) != 1:
        raise ValueError(f"expected one PROTOCOL_VERSION in {PROTOCOL_SOURCE}, found {len(matches)}")
    return matches[0]


def render(tag, version):
    return "\n".join(
        [
            "// GENERATED by scripts/protocol_fixture_version.py sync — do not edit by hand.",
            f"// PROTOCOL_VERSION from intent-hq/intentd {PROTOCOL_SOURCE} at {tag},",
            "// the newest release when generated; `check` flags a later protocol change.",
            "// Default protocolVersion for fake daemon hellos in tests (intent-hq/intent#7206).",
            f"// source-tag: {tag}",
            "nonisolated enum ProtocolFixtures {",
            f'    static let currentProtocolVersion = "{version}"',
            "}",
            "",
        ]
    )


def parse_rendered(content):
    tag, version = SOURCE_TAG.search(content), SWIFT_CONSTANT.search(content)
    return (tag.group(1), version.group(1)) if tag and version else None


def _get(url, accept):
    headers = {"Accept": accept, "User-Agent": "intent-ios protocol_fixture_version"}
    token = next((os.environ[n].strip() for n in ("GH_TOKEN", "GITHUB_TOKEN") if os.environ.get(n, "").strip()), None)
    if token:
        headers["Authorization"] = f"Bearer {token}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=30) as response:
        return response.read().decode()


RELEASE_TAG = re.compile(r"^v(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?(?:\+[0-9A-Za-z.-]+)?$")


def release_key(tag):
    """Semver ordering key; a prerelease sorts before its release."""
    major, minor, patch, pre = RELEASE_TAG.match(tag).groups()
    pre_key = tuple((0, int(p), "") if p.isdigit() else (1, 0, p) for p in pre.split(".")) if pre else ()
    return (int(major), int(minor), int(patch), pre is None, pre_key)


def newest_release_tag(releases):
    tags = [r["tag_name"] for r in releases if not r.get("draft") and RELEASE_TAG.match(r.get("tag_name", ""))]
    if not tags:
        raise ValueError(f"no published vX.Y.Z release in {REPO}")
    return max(tags, key=release_key)


def fetch_latest(get=_get):
    """Return (tag, protocol version) of the newest published intentd release."""
    releases = json.loads(get(f"https://api.github.com/repos/{REPO}/releases?per_page=50", "application/vnd.github+json"))
    tag = newest_release_tag(releases)
    source = get(f"https://api.github.com/repos/{REPO}/contents/{PROTOCOL_SOURCE}?ref={tag}", "application/vnd.github.raw")
    return tag, parse_rust_protocol_version(source)


def lint_violations(files):
    """files: {relative path: content}. Returns [(path, line, version, text)]."""
    found = []
    for path, content in sorted(files.items()):
        lines = content.split("\n")
        for index, text in enumerate(lines):
            versions = LITERAL.findall(text)
            if not versions or ESCAPE.search(text):
                continue
            if index and COMMENT_ONLY.match(lines[index - 1]) and ESCAPE.search(lines[index - 1]):
                continue
            found.extend((path, index + 1, version, text.strip()) for version in versions)
    return found


def scanned_files(root):
    files = {}
    for directory in SCANNED_DIRS:
        for path in sorted((root / directory).rglob("*.swift")):
            relative = path.relative_to(root).as_posix()
            if relative != OUTPUT.as_posix():
                files[relative] = path.read_text(encoding="utf-8")
    return files


def main(argv=None, root=ROOT, get=_get):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("command", choices=("sync", "check", "lint"))
    args = parser.parse_args(argv)
    output = root / OUTPUT
    if args.command == "lint":
        found = lint_violations(scanned_files(root))
        for path, line, version, text in found:
            print(f"{path}:{line}: literal protocolVersion {version}\n    {text}", file=sys.stderr)
        if found:
            print(
                "Use ProtocolFixtures.currentProtocolVersion so fake hellos follow each protocol bump. "
                f"For a test about a specific daemon version, keep the literal and add "
                f"`// {ESCAPE_TOKEN}: <reason>` on the line or the line above.",
                file=sys.stderr,
            )
            return 1
        print("Fixture protocol versions valid: tests default to ProtocolFixtures.currentProtocolVersion")
        return 0
    try:
        tag, version = fetch_latest(get)
    except Exception as error:  # network, API or parse failure
        print(f"error: could not read the latest intentd PROTOCOL_VERSION: {error}", file=sys.stderr)
        return 1
    expected = render(tag, version)
    if args.command == "sync":
        output.write_text(expected, encoding="utf-8")
        print(f"Wrote {OUTPUT}: intentd {tag} PROTOCOL_VERSION {version}")
        return 0
    current = output.read_text(encoding="utf-8") if output.exists() else ""
    recorded = parse_rendered(current)
    if recorded and recorded[1] == version:
        print(f"{OUTPUT} protocol {version} matches the newest intentd release ({tag})")
        return 0
    print(
        f"error: {OUTPUT} records protocol {recorded[1] if recorded else 'nothing'}, but intentd {tag} has "
        f"PROTOCOL_VERSION {version}. Run `python3 scripts/protocol_fixture_version.py sync` and commit the result.",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
