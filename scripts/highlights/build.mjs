// Regenerate with npm ci && npm run build from this directory.
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const directory = dirname(fileURLToPath(import.meta.url));
const output = resolve(directory, '../../Intent/Resources/Highlights');
const lockBytes = await readFile(resolve(directory, 'package-lock.json'));
const lock = JSON.parse(lockBytes);
const pkg = lock.packages['node_modules/@pierre/highlights'];
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
await mkdir(output, { recursive: true });
const result = await build({
  absWorkingDir: directory,
  entryPoints: ['entry.js'],
  outfile: resolve(output, 'highlights.bundle.js'),
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: ['safari17'],
  legalComments: 'inline',
  metafile: true,
  banner: { js: `/* Pierre Highlights ${pkg.version}. Generated by scripts/highlights/build.mjs. See NOTICE.txt. */` },
});
// A single JS file embeds Wasm and both themes; runtime asset fetches are forbidden.
if (Object.values(result.metafile.outputs).some(item => item.imports.length)) {
  throw new Error('Offline bundle unexpectedly has external imports');
}
const packageRoot = resolve(directory, 'node_modules/@pierre/highlights');
const notices = [
  'Intent iOS offline syntax tokenizer — third-party notices',
  `@pierre/highlights ${pkg.version}; Apache-2.0`,
  'https://github.com/pierrecomputer/pierre/tree/main/packages/highlights',
  'Only the Pierre Light and Pierre Dark themes are included. The upstream',
  'package notices are retained in full for provenance, including unused themes.',
  await readFile(resolve(packageRoot, 'LICENSE.md'), 'utf8'),
  await readFile(resolve(packageRoot, 'NOTICE.md'), 'utf8'),
];
await writeFile(resolve(output, 'NOTICE.txt'), `${notices.join('\n\n')}\n`);
const assets = {};
for (const name of ['highlights.bundle.js', 'index.html', 'NOTICE.txt']) {
  const bytes = await readFile(resolve(output, name));
  assets[name] = { bytes: bytes.length, sha256: hash(bytes) };
}
const manifest = {
  package: '@pierre/highlights', version: pkg.version,
  resolved: pkg.resolved, integrity: pkg.integrity,
  esbuild: lock.packages['node_modules/esbuild'].version,
  themes: ['pierre-light', 'pierre-dark'],
  packageLockSha256: hash(lockBytes),
  entrySha256: hash(await readFile(resolve(directory, 'entry.js'))),
  assets,
};
await writeFile(resolve(output, 'vendor.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Bundled Pierre Highlights ${pkg.version}: ${assets['highlights.bundle.js'].bytes} bytes.`);
